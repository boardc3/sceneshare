// Writes src/demoMedia.js from the files in public/media. Image sizes are read
// from the file headers, never typed by hand (doc 08, rule 2b: aspect ratio is law).
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

function jpegSize(buf) {
  let i = 2
  while (i < buf.length) {
    if (buf[i] !== 0xff) return null
    const marker = buf[i + 1]
    const len = buf.readUInt16BE(i + 2)
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) }
    }
    i += 2 + len
  }
  return null
}

const files = { before: 'public/media/demo-before.jpg', after: 'public/media/demo-after.jpg' }
let out = 'export const DEMO = null\n'
if (existsSync(files.before) && existsSync(files.after)) {
  const b = jpegSize(readFileSync(files.before))
  const a = jpegSize(readFileSync(files.after))
  if (b && a) {
    if (Math.abs(b.width / b.height - a.width / a.height) > 0.01) throw new Error('demo before/after aspect ratios differ')
    out = `export const DEMO = ${JSON.stringify({ before: { src: '/media/demo-before.jpg', ...b }, after: { src: '/media/demo-after.jpg', ...a } })}\n`
  }
}
writeFileSync('src/demoMedia.js', '// Generated by scripts/demo-media.mjs — do not edit.\n' + out)
console.log('demoMedia:', out.trim().slice(0, 120))
